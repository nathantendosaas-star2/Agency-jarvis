require("dotenv").config();
const express = require("express");
const helmet = require("helmet");
const path = require("path");
const app = express();
const PORT = process.env.PORT || 10000;
const publicDirectory = path.join(__dirname, "public");
app.use(helmet({ contentSecurityPolicy: false }));
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: false }));
app.get("/health", (_req, res) => res.status(200).json({ status: "ok", service: "agency-jarvis" }));
app.use(express.static(publicDirectory, { extensions: ["html"] }));
app.get("/", (_req, res) => res.sendFile(path.join(publicDirectory, "index.html")));
app.use("/api", (_req, res) => res.status(404).json({ error: "API endpoint not found." }));
app.use((_req, res) => res.status(404).sendFile(path.join(publicDirectory, "404.html")));
app.listen(PORT, "0.0.0.0", () => console.log(`Agency Jarvis is running on port ${PORT}`));